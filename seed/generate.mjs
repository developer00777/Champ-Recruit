// Builds seed/seed.sql from the demo's 20 sample roles so local dev starts with realistic data.
// Run: node seed/generate.mjs
import { writeFileSync } from 'node:fs';
import { jobs } from './demo-jobs.mjs';

const q = (v) => (v === null || v === undefined ? 'NULL' : typeof v === 'number' ? String(v) : typeof v === 'boolean' ? (v ? '1' : '0') : `'${String(v).replace(/'/g, "''")}'`);
const j = (v) => q(JSON.stringify(v));
const NOW = Date.now();
const DAY = 86400000;
const slug = (s) => s.toLowerCase().normalize('NFKD').replace(/[^\w\s-]/g, '').trim().replace(/[\s_-]+/g, '-');

const BASE_OFFERS = ['Structured onboarding and ongoing training from the L&D team', "Clear growth paths, including moves across the group's 20 businesses", 'Team events, recognition and leadership retreats'];
const companies = [
  { id: 'co_champions', slug: 'champions-group', name: 'Champions Group', locations: ['Bengaluru', 'Singapore'] },
  { id: 'co_lakeb2b', slug: 'lakeb2b', name: 'LakeB2B', locations: ['Bengaluru'] },
  { id: 'co_infometrics', slug: 'champion-infometrics', name: 'Champion InfoMetrics', locations: ['Bengaluru'] },
  { id: 'co_yacht', slug: 'champions-yacht-club', name: 'Champions Yacht Club', locations: ['Dubai'] },
  { id: 'co_ampliz', slug: 'ampliz', name: 'Ampliz', locations: ['Bengaluru'] },
];
const coByName = Object.fromEntries(companies.map((c) => [c.name, c]));

const family = (d) => d === 'Leadership' ? 'lead' : ['Sales', 'Lead Generation', 'Account Management'].includes(d) ? 'sales' : ['IT', 'Data & Research', 'Marketing'].includes(d) ? 'tech' : d === 'Customer Service' ? 'cx' : 'people';
const IDEAL = {
  sales: ['Experience selling data, SaaS or marketing services to US or UK buyers', 'Hands-on use of a sales engagement tool and a CRM such as HubSpot or Salesforce', 'A record of finishing near the top of a sales leaderboard'],
  people: ['Experience in a fast-growing, sales-driven organisation', 'Working knowledge of an HRMS or applicant tracking system', 'Comfort presenting numbers to managers'],
  tech: ['Experience with data or marketing tools used in B2B', 'Comfort automating repetitive work with scripts or formulas', 'Experience working directly with business users'],
  cx: ['Experience with international clients or guests', 'A second language', 'Familiarity with ticketing or booking systems'],
  lead: ['Experience across several business units or geographies', 'Board-level reporting experience', 'Experience designing commission and incentive frameworks'],
};
const LOOK = {
  sales: 'People who enjoy a target, pick up the phone without hesitation and learn fast from every no. If you like seeing your name climb a leaderboard, you will fit right in.',
  people: 'People who care about getting the detail right and making work better for everyone around them. You are organised, discreet and quick to follow through.',
  tech: 'Curious builders who like clean data and clear logic, and who want to see their work used every day by real teams.',
  cx: 'Calm, warm communicators who own a problem until it is solved and leave every client or guest better off.',
  lead: 'A commercial leader who builds strong teams, sets the operating rhythm and is accountable for the number.',
};
const NINETY = {
  lead: [['30', 'Meet every revenue leader and the top 20 clients', 'Stakeholder map shared'], ['60', 'Present a revenue diagnosis and plan to the CEO', 'Plan approved'], ['90', 'New targets, incentive frameworks and forecast rhythm live', 'Weekly forecast running']],
  sales: [['30', 'Product, ICP and CRM training, then shadow top performers', 'Certification passed'], ['60', 'Live calls on a ramped target with daily coaching', 'Ramp target met'], ['90', 'Full target and your first incentive cycle', 'Full target']],
  tech: [['30', 'Deliver your first piece of work with a buddy', 'First change shipped'], ['60', 'Own your workstream and its metrics', 'Workstream owned'], ['90', 'First review against role KPIs', 'KPIs met']],
  cx: [['30', 'Handle your first cases alongside a buddy', 'Quality score of 90% or more'], ['60', 'Own your queue end to end', 'SLA met'], ['90', 'First review against role KPIs', 'KPIs met']],
  people: [['30', 'Handle your first cases or batches alongside a buddy', 'Process checklist complete'], ['60', 'Own your process end to end', 'Turnaround time met'], ['90', 'First review against role KPIs', 'KPIs met']],
};
const TEAM = { sales: 'works to clear monthly targets with daily coaching', people: 'supports teams across the group', tech: 'builds and runs the systems the group relies on', cx: 'looks after clients and guests every day', lead: 'works closely with group leadership' };

const out = ['-- Generated by seed/generate.mjs. Safe to re-run: clears and reloads sample data.', 'PRAGMA defer_foreign_keys = on;'];
for (const t of ['audit_log', 'stage_history', 'applications', 'consents', 'job_alerts', 'posting_events', 'postings', 'post_copies', 'distribution_profiles', 'channel_connections', 'ai_runs', 'job_versions', 'jobs', 'candidates', 'users', 'companies']) out.push(`DELETE FROM ${t};`);

for (const c of companies) {
  const profile = {
    offers: BASE_OFFERS, locations: c.locations, shifts: ['Day shift', 'US shift', 'UK shift'],
    incentivePolicy: 'Sales and lead-generation roles earn a monthly incentive tied to clear, published targets.',
    culture: ['Open leaderboards', 'Early leadership for strong performers'],
    about: `${c.name} is part of Champions Group, a global group of 20 businesses across data, marketing, hospitality and more.`,
  };
  out.push(`INSERT INTO companies (id,slug,name,accent,profile,require_approval,created_at) VALUES (${q(c.id)},${q(c.slug)},${q(c.name)},'#F59A3C',${j(profile)},0,${NOW});`);
}
out.push(`INSERT INTO users (id,email,name,role,company_ids,created_at) VALUES ('usr_dev','recruiter@championsmail.com','Dev Recruiter','admin',NULL,${NOW});`);
out.push(`INSERT INTO users (id,email,name,role,company_ids,created_at) VALUES ('usr_hm','hiring.manager@championsmail.com','Hiring Manager','hiring_manager',NULL,${NOW});`);

for (const x of jobs) {
  const co = coByName[x.ent];
  const f = family(x.dept);
  const sections = {
    opportunity: `${x.seats > 1 ? `We're hiring ${x.seats} people for this role` : 'This is a single, high-impact position'} at ${x.ent}, based in ${x.loc} (${x.mode.toLowerCase()}, ${x.shift}). You'll join a ${x.dept} team that ${TEAM[f]}.`,
    responsibilities: x.resp, mustHave: x.req, niceToHave: IDEAL[f], whatWeLookFor: [LOOK[f]],
    first90Days: NINETY[f].map(([by, outcome, measure]) => ({ by, outcome, measure })),
    offers: [x.inc ? 'Fixed pay plus an incentive tied to clear, published targets' : 'Competitive fixed pay', ...BASE_OFFERS],
    skills: x.tags,
  };
  const posted = NOW - x.days * DAY;
  out.push(`INSERT INTO jobs (id,company_id,title,slug,department,location,work_mode,shift,exp_label,exp_band,seats,show_salary,incentive,tags,summary,status,current_version,owner_id,posted_at,created_at,updated_at) VALUES (${q(x.id)},${q(co.id)},${q(x.title)},${q(slug(x.title))},${q(x.dept)},${q(x.loc)},${q(x.mode)},${q(x.shift)},${q(x.exp)},${x.expBand},${x.seats},0,${q(x.inc)},${j(x.tags)},${q(x.sum)},'open',1,'usr_dev',${posted},${posted},${posted});`);
  out.push(`INSERT INTO job_versions (id,job_id,version,sections,source,author_id,created_at) VALUES (${q('jv_' + x.id)},${q(x.id)},1,${j(sections)},'human','usr_dev',${posted});`);
}

